export function getBranchCopyLine(axisId, branch) {
  const row = BRANCH_COPY[axisId];
  const line = row?.[branch];
  return line && line.length > 0 ? line : BRANCH_COPY_FALLBACK;
}

export function summarizeMatchedAxes(matchedAxes) {
  if (!matchedAxes?.length) return [];
  return matchedAxes.map((m) => getBranchCopyLine(m.axisId, m.branch));
}
